/**
 * 이 탐구가 답하려는 질문 한 문장. 요약표에 없으면 빈 문자열.
 *
 * 목록과 검색 결과가 레시피를 구별해 주는 데 쓰입니다. 예전에는 카드가
 * `applicationGuide`를 보여 주었는데, Phase 6의 41개는 그 값이 글자까지 같아
 * 물리 레시피 41장이 똑같은 설명을 달고 늘어섰습니다. 질문은 111개가 모두 다르고,
 * 무엇을 하는 탐구인지도 한 줄로 알려 줍니다.
 *
 * 가이드를 조립하는 `inquiryGuide.ts`가 아니라 이 파일에 두는 이유는 번들
 * 크기입니다. 레시피 카드가 그 파일을 가져오면 개념 사전과 스케치 서식기까지
 * 목록·검색 화면의 첫 번들에 함께 실립니다. 이 함수는 글자만 읽으므로
 * 가져올 것이 없습니다.
 */
export function inquiryQuestion(body: string): string {
  return /^\|\s*이 탐구가 답하려는 질문\s*\|\s*(.+?)\s*\|\s*$/m.exec(body)?.[1] ?? ''
}
